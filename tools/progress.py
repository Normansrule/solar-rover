#!/usr/bin/env python3
"""Draw the README's progress tracker from docs/progress.yaml.

    python3 tools/progress.py          # rewrite the SVGs and the README checklist
    python3 tools/progress.py --check  # exit 1 if they're out of date (CI)

Writes docs/img/anim/progress.svg (animated bars), docs/img/anim/roadmap.svg
(animated roadmap with the current step pulsing), docs/img/anim/hero.svg (the
animated banner) and the checklist between the progress markers in README.md.
GitHub shows SVG animations (SMIL and CSS) in README images, but not scripts.
"""
import html
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "docs", "progress.yaml")
ANIM = os.path.join(ROOT, "docs", "img", "anim")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- progress:start (generated by tools/progress.py) -->", "<!-- progress:end -->"

FONT = "font-family=\"-apple-system,BlinkMacSystemFont,'Segoe UI',Helvetica,Arial,sans-serif\""
BG, PANEL, INK, MUTED = "#0f1722", "#18222f", "#f2f5f8", "#8b98a8"
GREEN, AMBER, GREY, BLUE = "#2ecc71", "#ffc43d", "#3a4656", "#3b82f6"


def load():
    phases = yaml.safe_load(open(DATA, encoding="utf-8"))["phases"]
    for p in phases:
        st = [t["status"] for t in p["tasks"]]
        bad = set(st) - {"done", "next", "todo"}
        if bad:
            sys.exit(f"{p['name']}: unknown status {bad} in docs/progress.yaml")
        p["done"], p["total"] = st.count("done"), len(st)
        p["state"] = "done" if p["done"] == p["total"] else "active" if "next" in st or p["done"] else "todo"
    return phases


def esc(s):
    return html.escape(s, quote=True)


def svg(w, h, body, title):
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'role="img" aria-label="{esc(title)}" {FONT}>\n<title>{esc(title)}</title>\n{body}\n</svg>\n')


def progress_svg(phases):
    done = sum(p["done"] for p in phases)
    total = sum(p["total"] for p in phases)
    pct = round(100 * done / total)
    W, row = 860, 34
    H = 70 + row * len(phases)
    r, cx, cy = 74, 130, H / 2 + 6
    circ = 2 * 3.14159265 * r
    out = [f'<rect width="{W}" height="{H}" rx="16" fill="{BG}"/>',
           f'<text x="24" y="38" fill="{INK}" font-size="20" font-weight="700">Build progress</text>',
           f'<text x="{W - 24}" y="38" fill="{MUTED}" font-size="13" text-anchor="end">'
           f'{done} of {total} tasks done · from docs/progress.yaml</text>',
           # overall ring
           f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{GREY}" stroke-width="14"/>',
           f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{GREEN}" stroke-width="14" stroke-linecap="round" '
           f'transform="rotate(-90 {cx} {cy})" stroke-dasharray="{circ:.1f}" stroke-dashoffset="{circ:.1f}">'
           f'<animate attributeName="stroke-dashoffset" from="{circ:.1f}" to="{circ * (1 - done / total):.1f}" '
           f'dur="1.6s" begin="0.2s" fill="freeze" calcMode="spline" keySplines="0.2 0.8 0.2 1" keyTimes="0;1"/></circle>',
           f'<text x="{cx}" y="{cy + 12}" fill="{INK}" font-size="38" font-weight="800" text-anchor="middle" opacity="0">'
           f'{pct}%<animate attributeName="opacity" from="0" to="1" dur="0.6s" begin="1.2s" fill="freeze"/></text>',
           f'<text x="{cx}" y="{cy + 34}" fill="{MUTED}" font-size="12" text-anchor="middle">overall</text>']
    x0, bw = 290, 430
    for i, p in enumerate(phases):
        y = 62 + i * row
        f = p["done"] / p["total"]
        col = GREEN if p["state"] == "done" else AMBER if p["state"] == "active" else GREY
        out.append(f'<text x="{x0 - 12}" y="{y + 15}" fill="{INK}" font-size="14" font-weight="600" '
                   f'text-anchor="end">{esc(p["name"])}</text>')
        out.append(f'<rect x="{x0}" y="{y + 2}" width="{bw}" height="16" rx="8" fill="{PANEL}" stroke="{GREY}"/>')
        if f > 0:
            out.append(f'<rect x="{x0}" y="{y + 2}" width="0" height="16" rx="8" fill="{col}">'
                       f'<animate attributeName="width" from="0" to="{max(16, bw * f):.0f}" dur="1.1s" '
                       f'begin="{0.3 + 0.15 * i:.2f}s" fill="freeze" calcMode="spline" keySplines="0.2 0.8 0.2 1" '
                       f'keyTimes="0;1"/></rect>')
        if p["state"] == "active":      # shimmer on the phase being worked on
            out.append(f'<rect x="{x0}" y="{y + 2}" width="{bw}" height="16" rx="8" fill="none" stroke="{AMBER}" '
                       f'stroke-width="2"><animate attributeName="opacity" values="0.2;1;0.2" dur="1.6s" '
                       f'repeatCount="indefinite"/></rect>')
        label = "done" if p["state"] == "done" else f'{p["done"]}/{p["total"]}'
        out.append(f'<text x="{x0 + bw + 14}" y="{y + 15}" fill="{col if f else MUTED}" font-size="13" '
                   f'font-weight="600">{label}</text>')
    return svg(W, H, "\n".join(out), f"Build progress: {pct}% ({done} of {total} tasks)")


def roadmap_svg(phases):
    W, H = 860, 250
    n = len(phases)
    xs = [70 + i * (W - 140) / (n - 1) for i in range(n)]
    y = 110
    # the step being worked on: the phase holding the "next" task, else the first unfinished one
    cur = next((i for i, p in enumerate(phases) if any(t["status"] == "next" for t in p["tasks"])),
               next((i for i, p in enumerate(phases) if p["state"] != "done"), n - 1))
    nxt = next((t["task"] for p in phases for t in p["tasks"] if t["status"] == "next"), None)
    out = [f'<rect width="{W}" height="{H}" rx="16" fill="{BG}"/>',
           f'<text x="24" y="38" fill="{INK}" font-size="20" font-weight="700">Roadmap</text>',
           f'<text x="{W - 24}" y="38" fill="{MUTED}" font-size="13" text-anchor="end">'
           f'<tspan fill="{GREEN}">●</tspan> done   <tspan fill="{AMBER}">●</tspan> now   '
           f'<tspan fill="{GREY}">●</tspan> to do</text>',
           f'<line x1="{xs[0]}" y1="{y}" x2="{xs[-1]}" y2="{y}" stroke="{GREY}" stroke-width="6" stroke-linecap="round"/>']
    if cur > 0:   # finished stretch, with dashes flowing along it
        out.append(f'<line x1="{xs[0]}" y1="{y}" x2="{xs[0]}" y2="{y}" stroke="{GREEN}" stroke-width="6" '
                   f'stroke-linecap="round"><animate attributeName="x2" from="{xs[0]}" to="{xs[cur]:.0f}" dur="1.4s" '
                   f'fill="freeze"/></line>')
        out.append(f'<line x1="{xs[0]}" y1="{y}" x2="{xs[cur]:.0f}" y2="{y}" stroke="{BG}" stroke-width="2" '
                   f'stroke-dasharray="6 14" opacity="0.6"><animate attributeName="stroke-dashoffset" from="40" to="0" '
                   f'dur="1s" repeatCount="indefinite"/></line>')
    for i, (x, p) in enumerate(zip(xs, phases)):
        st = p["state"]
        col = GREEN if st == "done" else AMBER if i == cur or st == "active" else GREY
        delay = 0.2 + 0.18 * i
        g = [f'<g opacity="0"><animate attributeName="opacity" from="0" to="1" dur="0.4s" begin="{delay:.2f}s" '
             f'fill="freeze"/>']
        if i == cur:
            g.append(f'<circle cx="{x:.0f}" cy="{y}" r="18" fill="none" stroke="{AMBER}" stroke-width="3">'
                     f'<animate attributeName="r" values="18;30" dur="1.6s" repeatCount="indefinite"/>'
                     f'<animate attributeName="opacity" values="1;0" dur="1.6s" repeatCount="indefinite"/></circle>')
        g.append(f'<circle cx="{x:.0f}" cy="{y}" r="18" fill="{col if st == "done" or i == cur else PANEL}" '
                 f'stroke="{col}" stroke-width="3"/>')
        if st == "done":
            g.append(f'<path d="M{x - 8:.0f} {y} l5 6 l11 -12" fill="none" stroke="{BG}" stroke-width="3.5" '
                     f'stroke-linecap="round" stroke-linejoin="round"/>')
        else:
            g.append(f'<text x="{x:.0f}" y="{y + 5}" fill="{BG if i == cur else col}" font-size="14" '
                     f'font-weight="800" text-anchor="middle">{i + 1}</text>')
        g.append(f'<text x="{x:.0f}" y="{y + 44}" fill="{INK if st != "todo" or i == cur else MUTED}" font-size="14" '
                 f'font-weight="700" text-anchor="middle">{esc(p["name"])}</text>')
        g.append(f'<text x="{x:.0f}" y="{y + 62}" fill="{MUTED}" font-size="12" text-anchor="middle">'
                 f'{p["done"]}/{p["total"]}</text></g>')
        out += g
    # a little rover parked at the current step, bobbing
    rx = xs[cur]
    out.append(f'<g transform="translate({rx - 22:.0f} {y - 58})"><g>'
               f'<animateTransform attributeName="transform" type="translate" values="0 0;0 -3;0 0" dur="0.8s" '
               f'repeatCount="indefinite"/>'
               f'<rect x="4" y="0" width="30" height="4" rx="1" fill="{BLUE}"/>'
               f'<rect x="2" y="8" width="40" height="12" rx="3" fill="#7d8ea3"/>'
               f'<line x1="34" y1="8" x2="40" y2="-4" stroke="{AMBER}" stroke-width="3" stroke-linecap="round"/>'
               f'<line x1="40" y1="-4" x2="46" y2="4" stroke="{AMBER}" stroke-width="3" stroke-linecap="round"/>'
               f'<circle cx="10" cy="22" r="5" fill="#222"/><circle cx="34" cy="22" r="5" fill="#222"/></g></g>')
    if nxt:
        out.append(f'<rect x="24" y="{H - 46}" width="{W - 48}" height="30" rx="8" fill="{PANEL}" stroke="{AMBER}"/>')
        out.append(f'<text x="40" y="{H - 26}" fill="{AMBER}" font-size="14" font-weight="700">Next up:'
                   f'<tspan fill="{INK}" font-weight="400"> {esc(nxt)}</tspan></text>')
    return svg(W, H, "\n".join(out), "Roadmap" + (f", next up: {nxt}" if nxt else ""))


