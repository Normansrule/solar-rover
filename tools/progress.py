#!/usr/bin/env python3
"""Draw the README's progress tracker from docs/progress.yaml.

    python3 tools/progress.py          # rewrite the SVGs and the README checklist
    python3 tools/progress.py --check  # exit 1 if they're out of date (CI)

Writes docs/img/anim/progress.svg (one segment per task), docs/img/anim/hero.svg
(the banner) and the checklist between the progress markers in README.md.
Both pictures embed the app's own fonts (Barlow Semi Condensed and IBM Plex Sans,
from firmware/car/web/fonts), so they look the same on every machine.
"""
import base64
import html
import json
import os
import sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "docs", "progress.yaml")
ANIM = os.path.join(ROOT, "docs", "img", "anim")
README = os.path.join(ROOT, "README.md")
START, END = "<!-- progress:start (generated by tools/progress.py) -->", "<!-- progress:end -->"

FONTS = os.path.join(ROOT, "firmware", "car", "web", "fonts")   # SIL Open Font License, OFL-*.txt beside them
EASE_OUT, EASE_IN_OUT = "cubic-bezier(.23,1,.32,1)", "cubic-bezier(.77,0,.175,1)"
HAZARD = "#f5b800"   # the app's accent (firmware/car/web/index.html): the arm and "now"


def font_face(family, file, weight):
    data = base64.b64encode(open(os.path.join(FONTS, file), "rb").read()).decode()
    return (f'@font-face{{font-family:"{family}";font-weight:{weight};'
            f'src:url(data:font/woff2;base64,{data}) format("woff2")}}')


def load():
    phases = yaml.safe_load(open(DATA, encoding="utf-8"))["phases"]
    for p in phases:
        st = [t["status"] for t in p["tasks"]]
        bad = set(st) - {"done", "next", "todo"}
        if bad:
            sys.exit(f"{p['name']}: unknown status {bad} in docs/progress.yaml")
        p["done"], p["total"] = st.count("done"), len(st)
        p["state"] = "done" if p["done"] == p["total"] else "active" if "next" in st or p["done"] else "todo"
    return phases


def esc(s):
    return html.escape(s, quote=True)


def svg(w, h, body, title, style):
    # CSS animations, not SMIL, so prefers-reduced-motion is honoured. GitHub shows SVG
    # animations in README images but runs no scripts.
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" '
            f'role="img" aria-label="{esc(title)}">\n<title>{esc(title)}</title>\n<style>{style}\n'
            '@media (prefers-reduced-motion:reduce){*{animation:none!important}}</style>\n'
            f'{body}\n</svg>\n')


def progress_svg(phases):
    """One row of phases; each task is one segment, so the bar is the task list itself."""
    done = sum(p["done"] for p in phases)
    total = sum(p["total"] for p in phases)
    nxt = next((t["task"] for p in phases for t in p["tasks"] if t["status"] == "next"), None)
    W, H, M, gap = 960, 236 if nxt else 190, 40, 16
    cw = (W - 2 * M - gap * (len(phases) - 1)) / len(phases)
    style = (font_face("Barlow SC", "barlow-sc-700.woff2", 700)
             + font_face("Plex", "plex-sans-500.woff2", 500) + f'''
.bg{{fill:#18212b}} .ink{{fill:#edf1f5}} .ink2{{fill:#a7b4c2}} .now{{fill:{HAZARD}}}
.done{{fill:#c3ceda}} .todo{{fill:#33414f}} .next{{fill:{HAZARD}}}
@media (prefers-color-scheme:light){{.bg{{fill:#f3f5f7}} .ink{{fill:#121a23}} .ink2{{fill:#4b5967}}
 .now{{fill:#8a5a00}} .done{{fill:#53647a}} .todo{{fill:#c9d2db}}}}
text{{font-family:Plex,system-ui,sans-serif;font-weight:500}}
.h{{font-family:"Barlow SC",system-ui,sans-serif;font-weight:700}}
.seg{{transform-box:fill-box;transform-origin:left;animation:fill .5s {EASE_OUT} both}}
.next{{animation:fill .5s {EASE_OUT} both,breathe 2.4s ease-in-out 1.4s infinite alternate}}
@keyframes fill{{from{{transform:scaleX(0)}}}}
@keyframes breathe{{to{{opacity:.45}}}}''')
    out = [f'<rect class="bg" width="{W}" height="{H}" rx="16"/>',
           f'<text class="h ink" x="{M}" y="58" font-size="30">Build progress</text>',
           f'<text class="ink2" x="{W - M}" y="58" font-size="17" text-anchor="end">'
           f'{done} of {total} tasks done</text>']
    k = 0
    for i, p in enumerate(phases):
        x = M + i * (cw + gap)
        active = p["state"] == "active"
        out.append(f'<text class="{"ink" if p["state"] != "todo" else "ink2"}" x="{x:.1f}" y="106" '
                   f'font-size="17">{esc(p["name"])}</text>')
        n, sg = p["total"], 4
        sw = (cw - sg * (n - 1)) / n
        for j, t in enumerate(p["tasks"]):
            cls = {"done": "done", "next": "next", "todo": "todo"}[t["status"]]
            out.append(f'<rect class="seg {cls}" x="{x + j * (sw + sg):.1f}" y="120" width="{sw:.1f}" '
                       f'height="12" rx="3" style="animation-delay:{0.15 + 0.025 * k:.3f}s'
                       f'{"" if cls != "next" else f",{1.4:.1f}s"}"/>')
            k += 1
        label = f'{p["done"]}/{p["total"]}' + (' · now' if active else '')
        out.append(f'<text class="{"now" if active else "ink2"}" x="{x:.1f}" y="158" font-size="15">{label}</text>')
    if nxt:
        out.append(f'<text class="ink2" x="{M}" y="{H - 38}" font-size="17">Next up: '
                   f'<tspan class="ink">{esc(nxt)}</tspan></text>')
    return svg(W, H, "\n".join(out), f"Build progress: {done} of {total} tasks done"
               + (f", next up: {nxt}" if nxt else ""), style)


def crane_style():
    """The crane's colours and part styles, straight from the app's tokens.css (night shift)."""
    css = open(os.path.join(ROOT, "firmware", "car", "web", "tokens.css"), encoding="utf-8").read()
    i = css.index(":root{")
    dark = css[i:css.index("}", i) + 1]
    rules = "\n".join(line for line in css.splitlines() if line.startswith(".crane .") and "{" in line)
    return dark + "\n" + rules


def hero_svg():
    """The rover rolls in, stops, and unfolds its crane from park to ready: one moment, then it
    holds still. The drawing is the website's own (firmware/car/web/crane.js), exported to
    tools/rover_parts.json by tools/rover_svg.js, in millimetres, scaled into the banner."""
    W, H, gy = 960, 300, 262          # gy: ground line
    rx, k = 668, 0.78                 # where the deck centre stops, and px per mm
    parts = json.load(open(os.path.join(ROOT, "tools", "rover_parts.json"), encoding="utf-8"))
    SH = "translate(108px,-147.6px)"  # shoulder axis (crane.js SH_X, SH_Z)
    park, ready = (110, 120, -70), (45, 60, -10)          # shoulder, elbow, wrist (arm.cpp)
    joint = lambda base, a: f"{base} rotate({a}deg)"
    sh0, sh1 = joint(SH, -park[0]), joint(SH, -ready[0])
    el0, el1 = joint("translate(100px,0)", park[1]), joint("translate(100px,0)", ready[1])
    wr0, wr1 = joint("translate(90px,0)", -park[2]), joint("translate(90px,0)", -ready[2])
    style = (font_face("Barlow SC", "barlow-sc-700.woff2", 700)
             + font_face("Plex", "plex-sans-400.woff2", 400) + crane_style() + f'''
text{{font-family:Plex,system-ui,sans-serif}}
.title{{font-family:"Barlow SC",system-ui,sans-serif;font-weight:700}}
.rover{{animation:roll 1.4s {EASE_OUT} .2s both}}
.hub{{transform-box:fill-box;transform-origin:center;animation:spin 1.4s {EASE_OUT} .2s both}}
.j-sh,.j-el,.j-wr{{animation:.9s {EASE_IN_OUT} 1.4s both}}
.j-sh{{transform:{sh1};animation-name:sh}} .j-el{{transform:{el1};animation-name:el}} .j-wr{{transform:{wr1};animation-name:wr}}
.j-f1{{transform:translate(0,-11.4px)}} .j-f2{{transform:translate(0,11.4px)}}
@keyframes roll{{from{{transform:translateX(-170px)}}}}
@keyframes spin{{from{{transform:rotate(-520deg)}}}}
@keyframes sh{{from{{transform:{sh0}}}}} @keyframes el{{from{{transform:{el0}}}}} @keyframes wr{{from{{transform:{wr0}}}}}
@media (prefers-reduced-motion:reduce){{.rover,.hub,.j-sh,.j-el,.j-wr{{animation:none}}}}''')
    body = f'''<defs><clipPath id="frame"><rect width="{W}" height="{H}" rx="16"/></clipPath></defs>
<g clip-path="url(#frame)">
<rect width="{W}" height="{H}" fill="#19222c"/>
<circle cx="560" cy="62" r="26" fill="#ffcf4a"/>
<rect y="{gy}" width="{W}" height="{H - gy}" fill="#11171e"/>
<g class="rover"><g class="crane" transform="translate({rx} {gy}) scale({k})">
<g class="parts">{parts["body"]}</g><g class="parts">{parts["arm"]}</g>
</g></g>
<text class="title" x="48" y="132" fill="#edf1f5" font-size="76">Solar Rover</text>
<text x="50" y="176" fill="#b9c5d1" font-size="20">3D-printed, solar-charged, with a crane arm.</text>
<text x="50" y="206" fill="#b9c5d1" font-size="20">Drive it yourself, or let a learning agent take over.</text>
</g>'''
    return svg(W, H, body, "Solar Rover: the rover rolls in under the sun and unfolds its crane arm", style)


def checklist_md(phases):
    done = sum(p["done"] for p in phases)
    total = sum(p["total"] for p in phases)
    lines = [START, "", f"**{done} of {total} tasks done.** Edit [docs/progress.yaml](docs/progress.yaml) and run "
             "`python3 tools/progress.py` to update this list and the chart above.", ""]
    for p in phases:
        open_ = " open" if p["state"] == "active" else ""
        now = " (now)" if p["state"] == "active" else ""
        lines.append(f'<details{open_}><summary><b>{esc(p["name"])}</b>{now}: '
                     f'{p["done"]} of {p["total"]}</summary>\n')
        lines += [f'- [{"x" if t["status"] == "done" else " "}] {t["task"]}'
                  + (" **(next)**" if t["status"] == "next" else "") for t in p["tasks"]]
        lines.append("\n</details>")
    lines += ["", END]
    return "\n".join(lines)


def main():
    phases = load()
    files = {os.path.join(ANIM, "progress.svg"): progress_svg(phases),
             os.path.join(ANIM, "hero.svg"): hero_svg()}
    readme = open(README, encoding="utf-8").read()
    if START not in readme or END not in readme:
        sys.exit(f"README.md needs the markers {START} and {END}")
    a, b = readme.index(START), readme.index(END) + len(END)
    files[README] = readme[:a] + checklist_md(phases) + readme[b:]

    stale = [f for f, s in files.items() if not os.path.exists(f) or open(f, encoding="utf-8").read() != s]
    if "--check" in sys.argv:
        if stale:
            sys.exit("out of date, run python3 tools/progress.py: " + ", ".join(os.path.relpath(f, ROOT) for f in stale))
        print("progress tracker is up to date")
        return
    os.makedirs(ANIM, exist_ok=True)
    for f in stale:
        open(f, "w", encoding="utf-8").write(files[f])
        print("wrote", os.path.relpath(f, ROOT))


if __name__ == "__main__":
    main()
